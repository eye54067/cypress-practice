import { user, password } from '../fixtures/user.json'
import product from '../fixtures/product.json'

describe('Cart Validation', () => {
    it('Cart badge and cart contents match the added items', () => {
        cy.login(user[0].username, password)
        cy.url().should('include', '/inventory.html')
        cy.get('.inventory_item_name').should('have.length', 6)
        cy.get('#add-to-cart-sauce-labs-backpack').click()
        cy.get('#add-to-cart-sauce-labs-bike-light').click()
        cy.get('.shopping_cart_link').click()
        cy.get('.cart_item').should('have.length', 2)
        cy.contains('.cart_item', product[0].name).within(() => {
            cy.get('.cart_quantity').should('have.text', '1')
            cy.get('.inventory_item_price').should('have.text', '$'+`${product[0].price}`)
            cy.get('.inventory_item_desc').should('have.text', `${product[0].description}`)
        })
        cy.contains('.cart_item', product[1].name).within(() => {
            cy.get('.cart_quantity').should('have.text', '1')
            cy.get('.inventory_item_price').should('have.text', '$'+`${product[1].price}`)
            cy.get('.inventory_item_desc').should('have.text', `${product[1].description}`)
        })
        cy.get('.cart_item').its('length').then((count) => {
            cy.get('.shopping_cart_badge').should('have.text', String(count))
        })
    })
    it('Cart persists after refresh', () => {
        cy.login(user[0].username, password)
        cy.url().should('include', '/inventory.html')
        cy.get('#add-to-cart-sauce-labs-backpack').click()
        cy.get('#add-to-cart-sauce-labs-bike-light').click()
        cy.get('.shopping_cart_link').click()
        cy.get('.cart_item').should('have.length', 2)
        cy.contains('.cart_item', product[0].name).within(() => {
            cy.get('.cart_quantity').should('have.text', '1')
            cy.get('.inventory_item_price').should('have.text', '$'+`${product[0].price}`)
            cy.get('.inventory_item_desc').should('have.text', `${product[0].description}`)
        })
        cy.contains('.cart_item', product[1].name).within(() => {
            cy.get('.cart_quantity').should('have.text', '1')
            cy.get('.inventory_item_price').should('have.text', '$'+`${product[1].price}`)
            cy.get('.inventory_item_desc').should('have.text', `${product[1].description}`)
        })
        cy.reload()
        cy.url().should('include', '/cart.html')
        cy.get('.cart_item').should('have.length', 2)
        cy.contains('.cart_item', product[0].name).within(() => {
            cy.get('.cart_quantity').should('have.text', '1')
            cy.get('.inventory_item_price').should('have.text', '$'+`${product[0].price}`)
            cy.get('.inventory_item_desc').should('have.text', `${product[0].description}`)
        })
        cy.contains('.cart_item', product[1].name).within(() => {
            cy.get('.cart_quantity').should('have.text', '1')
            cy.get('.inventory_item_price').should('have.text', '$'+`${product[1].price}`)
            cy.get('.inventory_item_desc').should('have.text', `${product[1].description}`)
        })
    })
    it('Continue Shopping keeps cart', () => {
        cy.login(user[0].username, password)
        cy.url().should('include', '/inventory.html')
        cy.get('#add-to-cart-sauce-labs-backpack').click()
        cy.get('#add-to-cart-sauce-labs-bike-light').click()
        cy.get('.shopping_cart_link').click()
        cy.get('.cart_item').should('have.length', 2)
        cy.contains('.cart_item', product[0].name).within(() => {
            cy.get('.cart_quantity').should('have.text', '1')
            cy.get('.inventory_item_price').should('have.text', '$'+`${product[0].price}`)
            cy.get('.inventory_item_desc').should('have.text', `${product[0].description}`)
        })
        cy.contains('.cart_item', product[1].name).within(() => {
            cy.get('.cart_quantity').should('have.text', '1')
            cy.get('.inventory_item_price').should('have.text', '$'+`${product[1].price}`)
            cy.get('.inventory_item_desc').should('have.text', `${product[1].description}`)
        })
        cy.get('#continue-shopping').click()
        cy.url().should('include', '/inventory.html')
        cy.get('.shopping_cart_link').click()
        cy.url().should('include', '/cart.html')
        cy.get('.cart_item').should('have.length', 2)
        cy.contains('.cart_item', product[0].name).within(() => {
            cy.get('.cart_quantity').should('have.text', '1')
            cy.get('.inventory_item_price').should('have.text', '$'+`${product[0].price}`)
            cy.get('.inventory_item_desc').should('have.text', `${product[0].description}`)
        })
        cy.contains('.cart_item', product[1].name).within(() => {
            cy.get('.cart_quantity').should('have.text', '1')
            cy.get('.inventory_item_price').should('have.text', '$'+`${product[1].price}`)
            cy.get('.inventory_item_desc').should('have.text', `${product[1].description}`)
        })
    })
    it('Cart contents after logout and login', () => {
        cy.login(user[0].username, password)
        cy.url().should('include', '/inventory.html')
        cy.get('#add-to-cart-sauce-labs-backpack').click()
        cy.get('.shopping_cart_link').click()
        cy.get('.cart_item').should('have.length', 1)
        cy.contains('.cart_item', product[0].name).within(() => {
            cy.get('.cart_quantity').should('have.text', '1')
            cy.get('.inventory_item_price').should('have.text', '$'+`${product[0].price}`)
            cy.get('.inventory_item_desc').should('have.text', `${product[0].description}`)
        })
        cy.get('#react-burger-menu-btn').click()
        cy.get('#logout_sidebar_link').should('be.visible').click()
        cy.url().should('eq', 'https://www.saucedemo.com/')
        cy.login(user[0].username, password)
        cy.url().should('include', '/inventory.html')
        cy.get('.shopping_cart_link').click()
        cy.get('.cart_item').should('have.length', 1)
        cy.contains('.cart_item', product[0].name).within(() => {
            cy.get('.cart_quantity').should('have.text', '1')
            cy.get('.inventory_item_price').should('have.text', '$'+`${product[0].price}`)
            cy.get('.inventory_item_desc').should('have.text', `${product[0].description}`)
        })
    })
    it('Remove item on cart page & Empty cart view', () => {
        cy.login(user[0].username, password)
        cy.url().should('include', '/inventory.html')
        cy.get('.inventory_item_name').should('have.length', 6)
        cy.get('#add-to-cart-sauce-labs-backpack').click()
        cy.get('#add-to-cart-sauce-labs-bike-light').click()
        cy.get('.shopping_cart_link').click()
        cy.get('.cart_item').should('have.length', 2)
        cy.get('.shopping_cart_badge').should('have.text', '2')
        cy.get('#remove-sauce-labs-bike-light').click()
        cy.get('#remove-sauce-labs-backpack').click()
        cy.get('.cart_item').should('have.length', 0)
        cy.get('.shopping_cart_badge').should('not.exist')
    })
    it('Checkout with an empty cart', () => {
        cy.login(user[0].username, password)
        cy.url().should('include', '/inventory.html')
        cy.get('.inventory_item_name').should('have.length', 6)
        cy.get('#add-to-cart-sauce-labs-backpack').click()
        cy.get('#add-to-cart-sauce-labs-bike-light').click()
        cy.get('.shopping_cart_link').click()
        cy.get('.cart_item').should('have.length', 2)
        cy.get('#remove-sauce-labs-bike-light').click()
        cy.get('#remove-sauce-labs-backpack').click()
        cy.get('.cart_item').should('have.length', 0)
        cy.get('#checkout').click()
        cy.url().should('eq', 'https://www.saucedemo.com/cart.html')
        .and('not.eq', 'https://www.saucedemo.com/checkout-step-one.html')
    })
})
